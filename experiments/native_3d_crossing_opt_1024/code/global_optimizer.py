"""Experiment C: global automatic crossing optimisation with Native 3D excursions.

Starts from the frozen E5 legal layout (1024/1024, 2606 crossings), iteratively
adds mid-body layer changes that strictly reduce the exact global same-layer
crossing count, and only ever keeps fully validated legal states.

Scale-up:
* ``C1`` the 10 highest-crossing movable routes (machinery check)
* ``C2`` the 50 highest-crossing movable routes
* ``C3`` every movable route with crossings (>= 577 routes), several sweeps
"""
