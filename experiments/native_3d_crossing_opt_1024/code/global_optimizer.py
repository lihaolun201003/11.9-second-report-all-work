# ------------------------------------------------------------------ helpers
def make_env(log=print):
    _payload, routes = N.load_routes()
    env = CC.NativeRouteSet(routes, log=log)
    return env, G.BboxCache(list(env.routes.values()))


def route_priority(env, events):
    counter = Counter()
    for event in events:
        counter[int(event['route_a'])] += 1
        counter[int(event['route_b'])] += 1
    movable = [rid for rid in counter
               if not N.is_manual_route(env.routes[rid]) and counter[rid] > 0]
    movable.sort(key=lambda rid: (-counter[rid], rid))
    return movable, counter


def snapshot(env):
    return {rid: copy.deepcopy(route) for rid, route in env.routes.items()}


def write_routes_payload(routes, path, experiment, extra=None):
    base = N.load_e5_payload()
    ordered = [routes[rid] for rid in sorted(routes)]
    native = [route for route in ordered
              if int(route.get('n_mid_transitions') or 0) > 0]
    payload = dict(base)
    payload['schema'] = 'native3d_routes_l3d_v1'
    payload['experiment'] = experiment
    payload['parent_experiment'] = 'NON_C4_CROSSING_OPT_1024/E5_joint_repair_final'
    payload['native_3d'] = dict(
        model='one body may own several flat segments on different heights',
        routes_with_mid_transitions=len(native),
        mid_transitions=sum(int(route.get('n_mid_transitions') or 0)
                            for route in native),
        geometry='exact R15 S-curves (fsd25d.path3d.make_transition)',
        note='generated by native3d.global_optimizer')
    if extra:
        payload['native_3d'].update(extra)
    payload['route_count'] = len(ordered)
    payload['routed'] = len(ordered)
    payload['failed'] = 0
    payload['routes'] = ordered
    payload['crossing_definition'] = (
        'every flat part grouped by its physical z, fslw strict D56 audit '
        '(multi-height aware); interface leads included')
    N.write_json(path, payload)
    return payload


def crossing_report(env, experiment):
    routes = [env.routes[rid] for rid in sorted(env.routes)]
    report = X.crossing_report(routes, planes=None, assignment_by_id={},
                               include_events=True, routes_path=None)
    report['experiment'] = experiment
    report['routed'] = len(routes)
    report['failed'] = 0
    return report


def transition_stats(env):
    routes = [env.routes[rid] for rid in sorted(env.routes)]
    native = [route for route in routes
              if int(route.get('n_mid_transitions') or 0) > 0]
    by_plane = Counter()
    by_route = {}
    footprint_total = 0.0
    for route in native:
        rid = int(route['route_id'])
        entries = []
        for excursion in route.get('excursions') or ():
            entries.append(dict(from_z=excursion.get('from_z'),
                                to_z=excursion.get('to_z'),
                                footprint_mm=excursion.get('footprint_mm'),
                                middle_mm=excursion.get('middle_mm'),
                                s_start_mm=excursion.get('s_start_mm'),
                                s_end_mm=excursion.get('s_end_mm')))
            by_plane[('%+.3f' % float(excursion.get('from_z')))] += 1
            footprint_total += float(excursion.get('footprint_mm') or 0.0)
        by_route[str(rid)] = entries
    return dict(schema='native3d_transition_stats_v1',
                routes_with_mid_transitions=len(native),
                mid_transitions=sum(int(route.get('n_mid_transitions') or 0)
                                    for route in native),
                excursions=sum(len(value) for value in by_route.values()),
                by_from_height=dict(sorted(by_plane.items())),
                total_footprint_mm=round(footprint_total, 3),
                per_route=by_route)


# ------------------------------------------------------------------ sweeps
def sweep(env, bbox_cache, events, strategy, max_excursions, log, deadline,
          route_subset=None, max_clusters=4, max_targets=3):
    order, counter = route_priority(env, events)
    if route_subset is not None:
        order = order[:int(route_subset)]
    improvements = []
    reasons = Counter()
    applied = 0
    started = time.time()
    for route_id in order:
        if time.time() > deadline:
            log('[C] time budget reached after %d/%d routes' % (applied, len(order)))
            break
        before_total = env.total()
        plan = BA.route_plan(env, route_id, events, strategy=strategy,
                             max_excursions=max_excursions,
                             bbox_cache=bbox_cache)
        for key, value in (plan.get('reasons') or {}).items():
            if isinstance(value, int):
                reasons[key] += value
            else:
                reasons[str(key)] += 1
        if plan.get('new_route') is None or int(plan.get('predicted_delta') or 0) >= 0:
            continue
        env.replace_route(plan['new_route'])
        bbox_cache.update(plan['new_route'])
        after_total = env.total()
        if after_total < before_total:
            applied += 1
            improvements.append(dict(route_id=int(route_id),
                                     delta=int(after_total - before_total),
                                     crossings_after=int(after_total),
                                     excursions=plan.get('excursions') or []))
        else:
            env.replace_route(env.routes[route_id]) if False else None
            # revert to the previous route record
            previous = _revert_route(env, bbox_cache, route_id)
            # previous record is the pre-change one stored by replace_route
    return dict(improvements=improvements, applied=applied,
                routes=len(order), reasons=dict(reasons),
                seconds=round(time.time() - started, 1),
                total=int(env.total()))


# route replacement history for a safe revert
_REVERT_STORE = {}


def _remember(env, route_id):
    _REVERT_STORE[int(route_id)] = copy.deepcopy(env.routes[int(route_id)])


def _revert_route(env, bbox_cache, route_id):
    route = _REVERT_STORE.get(int(route_id))
    if route is None:
        return None
    env.replace_route(route)
    if bbox_cache is not None:
        bbox_cache.update(route)
    return route


# ------------------------------------------------------------------ stage
def run_stage(stage_name, env, bbox_cache, events, strategy, sweeps,
              route_subset, max_excursions, log, exp_dir, deadline,
              max_clusters=4, max_targets=3):
    history = []
    best_total = int(env.total())
    best_routes = snapshot(env)
    for sweep_index in range(1, int(sweeps) + 1):
        log('[C] === %s sweep %d/%d (start total=%d) ==='
            % (stage_name, sweep_index, sweeps, env.total()))
        started = time.time()
        order, _counter = route_priority(env, events)
        subset = order if route_subset is None else order[:int(route_subset)]
        improvements = []
        reasons = Counter()
        applied = 0
        for route_id in subset:
            if time.time() > deadline:
                log('[C] time budget reached (%d routes processed)' % applied)
                break
            before_total = env.total()
            previous = copy.deepcopy(env.routes[route_id])
            plan = BA.route_plan(env, route_id, events, strategy=strategy,
                                 max_excursions=max_excursions,
                                 bbox_cache=bbox_cache)
            for key, value in (plan.get('reasons') or {}).items():
                if isinstance(value, int):
                    reasons[key] += value
                else:
                    reasons[str(key)] += 1
            if plan.get('new_route') is None or int(plan.get('predicted_delta') or 0) >= 0:
                continue
            env.replace_route(plan['new_route'])
            bbox_cache.update(plan['new_route'])
            after_total = env.total()
            if after_total < before_total:
                applied += 1
                improvements.append(dict(route_id=int(route_id),
                                         delta=int(after_total - before_total),
                                         crossings_after=int(after_total),
                                         excursions=[{key: item.get(key) for key in
                                                      ('target_plane', 'target_z',
                                                       'from_z', 's0', 's1',
                                                       'footprint_mm', 'middle_mm',
                                                       'cluster_count', 'delta')}
                                                     for item in plan.get('excursions') or []]))
            else:
                env.replace_route(previous)
                bbox_cache.update(previous)
        elapsed = time.time() - started
        record = dict(stage=stage_name, sweep=sweep_index,
                      start_total=best_total, end_total=int(env.total()),
                      net=sum(item['delta'] for item in improvements),
                      applied=applied, routes=len(subset),
                      seconds=round(elapsed, 1), reasons=dict(reasons),
                      improvements=improvements)
        history.append(record)
        log('[C] %s sweep %d: total=%d net=%+d applied=%d routes=%d (%.1fs)'
            % (stage_name, sweep_index, env.total(), record['net'], applied,
               len(subset), elapsed))
        if env.total() < best_total:
            validation = G.full_validate(list(env.routes.values()))
            if validation['violations'] == 0:
                best_total = int(env.total())
                best_routes = snapshot(env)
                log('[C] new best legal layout: %d crossings (validated)' % best_total)
            else:
                log('[C] WARNING sweep result has violations - reverting to best')
                env.routes = {rid: copy.deepcopy(route)
                              for rid, route in best_routes.items()}
                env.cache = CC.CrossingCache(list(env.routes.values()))
                env.plane_cache = CC.PlaneIndexCache(env.cache.plane_routes)
                bbox_cache = G.BboxCache(list(env.routes.values()))
        else:
            log('[C] %s sweep %d produced no improvement' % (stage_name, sweep_index))
            break
        # checkpoint every sweep
        _write_checkpoint(env, exp_dir, stage_name, sweep_index, log)
        if improvements and sum(item['delta'] for item in improvements) == 0:
            break
    return env, bbox_cache, history, best_total, best_routes


def _write_checkpoint(env, exp_dir, stage_name, sweep_index, log=print):
    ckpt_dir = exp_dir / 'checkpoints'
    ckpt_dir.mkdir(parents=True, exist_ok=True)
    path = ckpt_dir / ('%s_sweep_%02d_routes_l3d.json'
                       % (stage_name.lower(), sweep_index))
    write_routes_payload(env.routes, path,
                         '%s/%s_sweep_%02d' % (EXPERIMENT, stage_name, sweep_index),
                         extra=dict(total_crossings=int(env.total()),
                                    mid_transitions=sum(
                                        int(route.get('n_mid_transitions') or 0)
                                        for route in env.routes.values())))
    log('[C] checkpoint %s' % path)


# ------------------------------------------------------------------ main
def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--strategy', default='B4_multi_excursion')
    parser.add_argument('--max-excursions', type=int, default=2)
    parser.add_argument('--time-budget', type=float, default=420.0,
                        help='seconds per stage')
    args = parser.parse_args(argv)
    run_dir = N.RUN_DIR
    exp_dir = run_dir / EXPERIMENT
    for sub in ('', 'checkpoints', 'stages'):
        (exp_dir / sub).mkdir(parents=True, exist_ok=True)
    log_path = run_dir / 'logs' / 'experiment_C.log'
    log_path.parent.mkdir(parents=True, exist_ok=True)

    def log(message):
        line = time.strftime('%H:%M:%S') + ' [C] ' + str(message)
        print(line, flush=True)
        with open(log_path, 'a', encoding='utf-8') as handle:
            handle.write(line + '\n')

    started = time.time()
    env, bbox_cache = make_env(log=log)
    events = env.cache.crossing_events()
    log('start: total=%d' % env.total())
    stages = [
        ('C1_top10', dict(sweeps=1, route_subset=10, budget=40.0)),
        ('C2_top50', dict(sweeps=1, route_subset=50, budget=110.0)),
        ('C3_all', dict(sweeps=3, route_subset=None, budget=args.time_budget)),
    ]
    all_history = []
    stage_summaries = {}
    for stage_name, config in stages:
        stage_deadline = time.time() + float(config['budget'])
        env, bbox_cache, history, best_total, best_routes = run_stage(
            stage_name, env, bbox_cache, events, args.strategy,
            config['sweeps'], config['route_subset'], args.max_excursions,
            log, exp_dir, stage_deadline)
        all_history.extend(history)
        stage_summaries[stage_name] = dict(
            sweeps=len(history), total=int(env.total()),
            best_total=int(best_total),
            applied_total=sum(item['applied'] for item in history),
            net_total=sum(item['net'] for item in history),
            seconds=sum(item['seconds'] for item in history))
        log('[C] %s done: total=%d (best validated=%d)'
            % (stage_name, env.total(), best_total))
    # ---- finalize with the best legal snapshot
    final_routes = {rid: route for rid, route in env.routes.items()}
    validation = G.full_validate(list(final_routes.values()), log=log)
    clearance = G.measure_min_clearance(list(final_routes.values()), log=log)
    if validation['violations'] != 0:
        log('[C] FINAL INVALID - falling back to the last validated best')
        final_routes = {rid: copy.deepcopy(route)
                        for rid, route in best_routes.items()}
        env.routes = final_routes
        env.cache = CC.CrossingCache(list(final_routes.values()))
        env.plane_cache = CC.PlaneIndexCache(env.cache.plane_routes)
        validation = G.full_validate(list(final_routes.values()), log=log)
        clearance = G.measure_min_clearance(list(final_routes.values()), log=log)
    write_routes_payload(final_routes, exp_dir / 'routes_l3d.json',
                         EXPERIMENT, extra=dict(
                             total_crossings=int(env.total()),
                             mid_transitions=sum(
                                 int(route.get('n_mid_transitions') or 0)
                                 for route in final_routes.values())))
    report = crossing_report(env, EXPERIMENT)
    N.write_json(exp_dir / 'crossing_stats.json', report)
    transition = transition_stats(env)
    N.write_json(exp_dir / 'transition_stats.json', transition)
    N.write_json(exp_dir / 'failed_attempts.json', dict(
        schema='native3d_experiment_c_failures_v1',
        reasons_by_sweep={('%s_%d' % (item['stage'], item['sweep'])): item['reasons']
                          for item in all_history}))
    C.write_csv(exp_dir / 'optimization_history.csv',
                [dict(stage=item['stage'], sweep=item['sweep'],
                      start_total=item['start_total'], end_total=item['end_total'],
                      net=item['net'], applied=item['applied'],
                      routes=item['routes'], seconds=item['seconds'],
                      reasons=json.dumps(item['reasons'], ensure_ascii=False))
                 for item in all_history],
                ['stage', 'sweep', 'start_total', 'end_total', 'net',
                 'applied', 'routes', 'seconds', 'reasons'])
    native_routes = [route for route in final_routes.values()
                     if int(route.get('n_mid_transitions') or 0) > 0]
    summary = dict(
        schema='native3d_experiment_c_summary_v1',
        strategy=args.strategy,
        start_total=2606,
        final_crossings=int(env.total()),
        crossing_pairs=int(env.cache.total_pairs()),
        routes=len(final_routes),
        routes_with_mid_transitions=len(native_routes),
        mid_transitions=sum(int(route.get('n_mid_transitions') or 0)
                            for route in native_routes),
        total_length_mm=round(sum(float(route.get('length_mm') or 0.0)
                                  for route in final_routes.values()), 3),
        baseline_length_mm=round(sum(float(route.get('length_mm') or 0.0)
                                     for route in N.load_e5_payload()['routes']), 3),
        validation=validation,
        min_3d_clearance=clearance,
        stages=stage_summaries,
        history=all_history,
        seconds=round(time.time() - started, 1))
    N.write_json(exp_dir / 'summary.json', summary)
    # copy the 21-height model files for the validator
    for name in ('assignment_1024.csv', 'layer_planes.json',
                 'process_rules.json', 'physical_layer_stack.json'):
        source = N.E5_DIR / name
        if source.is_file():
            (exp_dir / name).write_bytes(source.read_bytes())
    log('[C] FINAL crossings=%d (start 2606), routes=%d native=%d '
        'mid_transitions=%d validation=%s min_clear=%s'
        % (env.total(), len(final_routes), len(native_routes),
           summary['mid_transitions'],
           'ok' if validation['violations'] == 0 else 'FAILED',
           clearance.get('min_3d_clearance_mm')))
    return summary


if __name__ == '__main__':
    main()
