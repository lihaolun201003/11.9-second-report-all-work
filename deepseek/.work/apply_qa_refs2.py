def replace_line(anchor, newline, label):
    idx = [i for i, l in enumerate(lines) if anchor in l]
    if len(idx) != 1:
        print('FAIL replace', label, len(idx)); sys.exit(1)
    lines[idx[0]] = newline


def insert_after(anchor, newlines, label):
    idx = [i for i, l in enumerate(lines) if anchor in l]
    if len(idx) != 1:
        print('FAIL insert', label, len(idx)); sys.exit(1)
    for j, nl in enumerate(newlines):
        lines.insert(idx[0] + 1 + j, nl)


